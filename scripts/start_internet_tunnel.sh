#!/bin/bash
# ==============================================================================
# UNIBLE SALE - 원클릭 무료 보안 인터넷 공개 터널 스크립트
# 외부 현장, 거래처, 아버지 컴퓨터 등 전 세계 어디서나 접속할 수 있는
# 보안 HTTPS 인터넷 주소를 발급합니다.
# ==============================================================================

PORT=3000
echo "=========================================================="
echo "  UNIBLE SALE (유니블 세일) 실시간 인터넷 접속 터널 가동"
echo "  도입 업체: 동산화스너"
echo "=========================================================="

# 1. 3000 포트 가동 여부 확인
if ! lsof -i :$PORT > /dev/null 2>&1; then
    echo "⚠️ 로컬 ERP 서버(포트 $PORT)가 실행되어 있지 않습니다."
    echo "-> 백그라운드에서 Next.js ERP 서버를 시작합니다..."
    npm run dev &
    sleep 4
fi

echo "✅ 로컬 ERP 서버 확인 완료 (포트 $PORT)"
echo "----------------------------------------------------------"
echo "📡 외부 인터넷 공개 HTTPS 터널 생성 중..."
echo "----------------------------------------------------------"

# npx localtunnel을 통한 무료 보안 HTTPS 주소 생성
npx localtunnel --port $PORT
